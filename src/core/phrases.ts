// テンプレート生成用の言い回し辞書。
// 選択肢ラベルをそのまま穴埋めすると日本語が崩れる（「また来たいのがよかったです」等）ので、
// 選択肢ごとに文の形を用意しておく。キーは survey-presets.json の業種 ID・選択肢 ID。
// ラベルの意味の範囲を超える事実は書かない。

export interface ScenePhrase {
  /** 来店の一文（です・ます、句点なし）。{c} に Q2 の前置き（ContextPhrase.pre）が入る。無ければ Q2 は別文で言う */
  v: string;
  /** 名詞 */
  n: string;
  /** 「〜、こちらを選びました」の前半 */
  why: string;
  /** 「〜の方」。どんな人に向くかを書くとき */
  who: string;
}

export interface ContextPhrase {
  /** ScenePhrase.v の {c} に入る前置き */
  pre: string;
  /** 単独の一文 */
  s: string;
  /** 「〜の方」 */
  who: string;
}

export interface GoodPhrase {
  /** 述語の一文: 料理がおいしかったです */
  a: string;
  /** 連用形: 料理がおいしく */
  te: string;
  /** 名詞句: 料理のおいしさ */
  n: string;
  /** 少しふくらませた一文（ラベルの意味の範囲で） */
  x: string[];
  /** closing: 締めで使う（また来たい等） / impression: 入った瞬間の印象として書ける */
  tag?: "closing" | "impression";
  /** 「想像以上」「最初に感じたのは」と言えない出来事型の項目 */
  event?: boolean;
}

export interface ConcernPhrase {
  /** 一文: 待ち時間が少し長かったです */
  a: string;
  /** 名詞句。「〜は少し気になりました」「気になったのは〜です」に入る */
  n: string;
}

export interface CategoryPhrases {
  /** 「〜を選びました」の目的語 */
  place: string;
  /** 「〜に向いている◯◯だと思います」 */
  noun: string;
  /** 「〜、まず◯◯が印象的でした」 */
  entering: string;
  /** Q2 が来店理由の業種（「〜のために、こちらを選びました」と言える） */
  contextIsReason?: boolean;
  scene: Record<string, ScenePhrase>;
  context: Record<string, ContextPhrase>;
  good: Record<string, GoodPhrase>;
  concern: Record<string, ConcernPhrase>;
}

const sc = (v: string, n: string, why: string, who: string): ScenePhrase => ({ v, n, why, who });
const cx = (pre: string, s: string, who: string): ContextPhrase => ({ pre, s, who });
const g = (a: string, te: string, n: string, x: string | string[] = [], opts: Partial<GoodPhrase> = {}): GoodPhrase => ({
  a,
  te,
  n,
  x: Array.isArray(x) ? x : [x],
  ...opts,
});
const imp = { tag: "impression" } as const;
const ev = { event: true } as const;
const closing = (a: string, te: string, x: string[]): GoodPhrase => ({ a, te, n: "", x, tag: "closing", event: true });
const cc = (a: string, n: string): ConcernPhrase => ({ a, n });

